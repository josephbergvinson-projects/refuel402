function configuredQuoteMirror(raw: string | undefined, publicMirror: string): string {
  const value = raw?.trim() || publicMirror;
  const quote = new URL(value);
  if (quote.protocol !== "https:") throw new Error("quote Mirror endpoint must use HTTPS");
  return quote.toString().replace(/\/$/, "");
}

