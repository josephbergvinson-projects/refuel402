type WhitelistFile = {
  tokens: {
    symbol: string;
    tokenId: string;
    evmAddress: Address;
    decimals: number;
    poolFee: number;
    route?: { toToken: Address; fee: number }[];
    suggestedMaxAmountIn: string;
    bridge: string | null;
    supported?: boolean;
    poolTvlUsd: number | null;
    impactBps: number;
    maxFuelHbar?: number;
  }[];
};

/** The vetted hops from `token` to WHBAR (explicit route, or the direct default). */
export function tokenRoute(token: SupportedToken, whbar: Address): RouteHop[] {
  return token.route && token.route.length > 0
    ? token.route
    : [{ toToken: whbar, fee: token.poolFee }];
}

/**
 * Load the liquidity-vetted whitelist generated by scripts/build-whitelist.ts.
 * Regenerate it from live SaucerSwap analytics; the service reads it at boot so
 * the token set tracks real liquidity instead of a hand-maintained list.
 */
export function loadTokens(network: "testnet" | "mainnet"): SupportedToken[] {
  const file = path.join(root, "config", `whitelist.${network}.json`);
  if (!fs.existsSync(file)) return FALLBACK_TOKENS;
  const wl = JSON.parse(fs.readFileSync(file, "utf8")) as WhitelistFile;
  // Defunct bridge remnants remain in historical bridge metadata for warning
  // holders, but are never admitted to a fuelable network whitelist.
  const tokens = wl.tokens.filter((t) => t.supported !== false && t.bridge !== "hashport").map((t) => ({
    tokenId: t.tokenId,
    evmAddress: t.evmAddress,
    symbol: t.symbol,
    decimals: t.decimals,
    poolFee: t.poolFee,
    route: t.route,
    maxAmountIn: BigInt(t.suggestedMaxAmountIn),
    impactBps: t.impactBps,
    maxFuelHbar: t.maxFuelHbar,
    bridge: t.bridge ?? undefined,
  }));
  return tokens.length ? tokens : FALLBACK_TOKENS;
}

/** Per-network vetted token lists, loaded once (read endpoints serve both). */
const TOKENS_BY_NET: Record<NetworkName, SupportedToken[]> = {
  testnet: loadTokens("testnet"),
  mainnet: loadTokens("mainnet"),
};
export function tokensFor(network: NetworkName): SupportedToken[] {
  return TOKENS_BY_NET[network];
}

/** Full liquidity-vetted token list for the EXECUTION network (testnet). */
export const ALL_TOKENS: SupportedToken[] = TOKENS_BY_NET[
  (process.env.HEDERA_NETWORK as NetworkName) ?? "testnet"
];

// Symbol-keyed map for ergonomic lookups (TOKENS.USDC). If two whitelisted
// tokens share a symbol, the map can only hold one — but the policy allowlist
// uses ALL_TOKENS, so no token is ever silently dropped from what we sponsor.
export const TOKENS: Record<string, SupportedToken> = Object.fromEntries(
  ALL_TOKENS.map((t) => [t.symbol, t]),
);

/** Bridge provenance map (config/bridges.json), for stranded-account UX. */
export function loadBridges(): Record<string, { displayName: string; tokens: Record<string, { symbol: string; fuelableToday: boolean; note?: string }> }> {
  const file = path.join(root, "config", "bridges.json");
  if (!fs.existsSync(file)) return {};
  const raw = JSON.parse(fs.readFileSync(file, "utf8")) as Record<string, unknown>;
  delete raw._comment;
  return raw as never;
}

export function policyConfig(network: NetworkName = "testnet"): PolicyConfig {
  const n = NETWORKS[network];
  return {
    chainId: n.chainId,
    router: n.router,
    whbar: n.whbarToken,
    tokens: tokensFor(network),
    maxGasLimit: BigInt(process.env.MAX_GAS_LIMIT ?? 2_000_000),
    // associate()/approve() on an HTS facade measured ~785k gas each (they carry
    // a ~$0.05 HTS HAPI fee rolled into gas); cap a little above that.
    associateGasLimit: BigInt(process.env.ASSOCIATE_GAS_LIMIT ?? 1_000_000),
    approveGasLimit: BigInt(process.env.APPROVE_GAS_LIMIT ?? 1_000_000),
    maxDeadlineSkewSec: Number(process.env.MAX_DEADLINE_SKEW_SEC ?? 900),
    // x402 payment window (180s) + settlement + submission slack
    minDeadlineBufferSec: Number(process.env.MIN_DEADLINE_BUFFER_SEC ?? 240),
    routeFor: (t) => tokenRoute(t, n.whbarToken),
  };
}

